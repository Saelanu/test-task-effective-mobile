def missing_number(nums):
    """
    Находит пропущенное число в последовательности от 1 до n.

    Алгоритм:
    1. Вычисляем ожидаемую сумму от 1 до n по формуле: n*(n+1)/2
    2. Вычисляем фактическую сумму элементов списка
    3. Разница = пропущенное число

    Сложность:
    - Время: O(n) - один проход для суммирования
    - Память: O(1) - используем только несколько переменных

    Пример:
    >>> missing_number([1, 2, 3, 4, 5, 6, 8, 9, 10, 11])
    7
    """
    n = len(nums) + 1  # полная длина последовательности
    expected_sum = n * (n + 1) // 2
    actual_sum = sum(nums)
    return expected_sum - actual_sum

sequence = [1, 2, 3, 4, 5, 6, 8, 9, 10, 11]
missing = missing_number(sequence)
print(f"Пропущенное число в последовательности {sequence} равно {missing}")